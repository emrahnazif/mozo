import { readFileSync } from 'node:fs';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import { defineConfig } from 'vite';

// Every package compiled into the bundle is redistributed with it, so its licence ships beside it
// as `<name>-LICENSE`: the Heroicons inlined as icons, Svelte Flow and Svelte, and dagre, which
// lays out a workflow whose nodes have no position. A package added to the bundle goes here too.
const BUNDLED = {
  heroicons: 'heroicons/LICENSE',
  dagre: '@dagrejs/dagre/LICENSE',
  graphlib: '@dagrejs/graphlib/LICENSE',
  'xyflow-svelte': '@xyflow/svelte/LICENSE',
  'xyflow-system': '@xyflow/system/LICENSE',
  svelte: 'svelte/LICENSE.md',
};
const licences = {
  name: 'licences',
  generateBundle() {
    for (const [name, file] of Object.entries(BUNDLED)) {
      this.emitFile({ type: 'asset', fileName: `${name}-LICENSE`,
                      source: readFileSync(`node_modules/${file}`, 'utf8') });
    }
  },
};

// One build, one bundle: `editor.js`, which a page imports to `mount` the editor, and the
// `editor.css` it attaches to itself. Stable names, because a host imports them by name; the
// router serves them with `Cache-Control: no-cache` so an upgrade is never hidden by a cache.
// mozo's own page is generated by the router (mozo/workflow/api.py), not built here.
export default defineConfig({
  plugins: [svelte(), licences],
  build: {
    outDir: '../mozo/workflow/static/assets',
    emptyOutDir: true,
    copyPublicDir: false,
    modulePreload: false,
    // An application build of one script rather than library mode, which leaves an ES bundle
    // unminified -- and that keeps `mount`, the one export a page imports.
    rollupOptions: {
      input: 'src/editor.js',
      preserveEntrySignatures: 'strict',
      output: {
        entryFileNames: 'editor.js',
        assetFileNames: (asset) => asset.name?.endsWith('.css') ? 'editor.css' : '[name][extname]',
      },
    },
  },
  server: {
    port: 5173,
    proxy: { '/workflow': 'http://localhost:8000' },
  },
});
